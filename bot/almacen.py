"""Perfiles y registro de mensajes en la base de datos de la barbería, para cuando el bot corre en Vercel.

Allá el disco del contenedor se borra en cada despliegue, así que lo que en el computador va en bot/datos/ se
guarda en el esquema `bot` de la misma base de Supabase. Se usa solo si existe la variable DATABASE_URL.
"""
import json

from .perfiles import Perfiles

ESQUEMA = """
CREATE SCHEMA IF NOT EXISTS bot;
CREATE TABLE IF NOT EXISTS bot.perfil (
    uid   TEXT PRIMARY KEY,           -- cuenta de Telegram
    datos JSONB NOT NULL
);
CREATE TABLE IF NOT EXISTS bot.mensaje (
    id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    datos JSONB NOT NULL              -- fecha, texto y lo que entendió el clasificador, sin el nombre
);
"""


def _conectar(url):
    import psycopg
    # prepare_threshold=None: el pooler de Supabase en modo transacción no admite sentencias preparadas
    return psycopg.connect(url, prepare_threshold=None, autocommit=True)


class PerfilesBD(Perfiles):
    """Los mismos perfiles de Perfiles, guardados en bot.perfil en vez de un archivo JSON."""

    def __init__(self, url):
        self.ruta, self.url = None, url
        with _conectar(url) as conexion:
            conexion.execute(ESQUEMA)
            self.datos = {uid: datos for uid, datos in conexion.execute("SELECT uid, datos FROM bot.perfil")}

    def borrar(self, uid):
        self.datos.pop(str(uid), None)
        with _conectar(self.url) as conexion:
            conexion.execute("DELETE FROM bot.perfil WHERE uid = %s", (str(uid),))

    def guardar(self):
        with _conectar(self.url) as conexion:
            for uid, datos in self.datos.items():
                conexion.execute("INSERT INTO bot.perfil (uid, datos) VALUES (%s, %s::jsonb) "
                                 "ON CONFLICT (uid) DO UPDATE SET datos = EXCLUDED.datos",
                                 (uid, json.dumps(datos, ensure_ascii=False)))


class RegistroBD:
    """Recibe cada mensaje ya sin el nombre de quien lo escribió y lo guarda en bot.mensaje."""

    def __init__(self, url):
        self.url = url

    def __call__(self, registro):
        with _conectar(self.url) as conexion:
            conexion.execute("INSERT INTO bot.mensaje (datos) VALUES (%s::jsonb)",
                             (json.dumps(registro, ensure_ascii=False),))
